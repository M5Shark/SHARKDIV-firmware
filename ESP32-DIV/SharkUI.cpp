// SharkUI.cpp — M5SHARK-style boot splash and menu chrome for SHARKDIV.
// Ported from github.com/M5Shark/M5Shark (MIT): the mark is drawn as
// character cells (6x8 GLCD font) over a noise field, decoded two rows per
// frame, glitched, then locked. ~1 KB of flash, no frame buffer.
// Mark art: the user-supplied "ASCII Skull Jaw" piece, scaled to the grid.

