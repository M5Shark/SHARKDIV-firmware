// The user's "ASCII Skull Jaw" piece at native proportions — the characters
// ARE the art, drawn verbatim (non-ASCII strokes mapped to their CP437
// glyphs). Never resample this; scaled masks destroy line art.
const uint8_t ART_COLS = 25;
const uint8_t ART_ROWS = 16;
const int16_t CELL_W = 6;
const int16_t CELL_H = 8;
const int16_t ART_X = 45;   // (240 - 25*6) / 2
const int16_t ART_Y = 118;  // art block spans y 118..246
const uint16_t WD_KEEP_COLOR = 0;

const char* const skull_art[ART_ROWS] = {
  "         _.,,,.._",
  "      ,d$$$$$$$SSIi:.",
  "    ,S$$$$$$$$$$$$SIIi:.",
  "   jI$$$$$$$$$$$$$SISSi:.",
  "  ,S$$$$$$$$$$$$$$$$$$Ii:",
  " j\xA6?$$$$$$$$$$$$$$$S$$Ii",
  " :  ?$$$$$$$$$$S7IISS$$I:",
  "j_ /$$7`\xF84$$$$7:iIS$$$$I'",
  "\xA6?\"?$$:   `$k :iIIS$$$7'",
  " \xB3  ?$L,  ,d$     $$$7'",
  ",d._J$$$$S$$$L,_\xF9'$$",
  "?$$$$$$k:?$$\xA6\xF8,  \xF8'",
  "\\:`\xF8\xA7\xA6\xF8^`:jIS7",
  "j$k,i;/_,oSSI'",
  "?SSS$$$$$?\xA6`",
  " `\xA6\xA7\xA6\xF8\"`"
};

const uint8_t noise_glyphs[16] = {'0', 'M', 'g', 'p', 'N', '#', '%', '&',
                                  '$', '4', 'X', 'W', '8', 'q', 'R', 'j'};

uint8_t artGlyph(uint8_t col, uint8_t row) {
  if (row >= ART_ROWS)
    return 0;
  const char* l = skull_art[row];
  const uint8_t len = (uint8_t)strlen(l);
  if (col >= len)
    return 0;
  const uint8_t ch = (uint8_t)l[col];
  return (ch == ' ') ? 0 : ch;
}

void drawArtCell(uint8_t col, uint8_t row, uint16_t color, int16_t dx = 0) {
  const uint8_t g = artGlyph(col, row);
  if (!g)
    return;
  tft.drawChar(ART_X + col * CELL_W + dx, ART_Y + row * CELL_H, g, color,
               TFT_BLACK, 1);
}

void drawArtRows(int16_t first_row, int16_t last_row, uint16_t color,
                 int16_t dx = 0) {
  if (first_row < 0)
    first_row = 0;
  if (last_row >= ART_ROWS)
    last_row = ART_ROWS - 1;
  for (int16_t row = first_row; row <= last_row; row++)
    for (uint8_t col = 0; col < ART_COLS; col++)
      drawArtCell(col, (uint8_t)row, color, dx);
}

void clearRows(int16_t first_row, int16_t rows) {
  tft.fillRect(ART_X - 6, ART_Y + first_row * CELL_H, ART_COLS * CELL_W + 12,
               rows * CELL_H, TFT_BLACK);
}

// Scatter of terminal glyphs over empty cells so the art keeps breathing
// while it decodes — the strokes themselves are never overwritten.
void churnNoise(int16_t first_row, int16_t last_row, uint16_t salt) {
  for (uint8_t i = 0; i < 30; i++) {
    const uint16_t noise = wdHash(i, salt, 0x5A5A);
    const uint8_t col = noise % ART_COLS;
    const int16_t row = first_row + (int16_t)((noise >> 6) % (uint16_t)(last_row - first_row + 1));
    if (row < 0 || row >= ART_ROWS || artGlyph(col, (uint8_t)row))
      continue;
    tft.drawChar(ART_X + col * CELL_W, ART_Y + row * CELL_H,
                 (uint8_t)noise_glyphs[(noise >> 11) & 0x0F],
                 ((noise >> 4) & 0x07) ? wdMarkC() : wdEdge(), TFT_BLACK, 1);
  }
}

void drawCarrierNoise(uint16_t salt) {
  for (uint8_t i = 0; i < 70; i++) {
    const uint16_t noise = wdHash(i, salt, 0xA5A5);
    const uint8_t col = noise % ART_COLS;
    const uint8_t row = (noise >> 6) % ART_ROWS;
    tft.drawChar(ART_X + col * CELL_W, ART_Y + row * CELL_H,
                 (uint8_t)noise_glyphs[(noise >> 11) & 0x0F],
                 ((noise >> 4) & 0x07) ? wdGrey() : wdAccentDim(),
                 TFT_BLACK, 1);
  }
}

void drawHeader(int16_t width) {
  const int16_t badgeW = (int16_t)tft.textWidth("SHARKDIV", 2) + 10;
  tft.fillRect(0, 0, width, 22, TFT_BLACK);
  tft.fillRect(0, 0, badgeW, 20, wdAccent());
  tft.setTextDatum(MC_DATUM);
  tft.setTextColor(TFT_BLACK, wdAccent());
  tft.drawString("SHARKDIV", badgeW / 2, 10, 2);
  tft.setTextDatum(ML_DATUM);
  tft.setTextColor(wdAccent(), TFT_BLACK);
  tft.drawString("// ctOS", badgeW + 6, 10, 1);
  tft.setTextDatum(MR_DATUM);
  tft.setTextColor(wdWarn(), TFT_BLACK);
  tft.drawString(String("SYS ") + ESP32DIV_VERSION, width - 6, 10, 1);
  tft.setTextDatum(TL_DATUM);
  tft.drawFastHLine(0, 21, width, wdEdge());
  tft.drawFastHLine(0, 21, badgeW, wdAccent());
}

void drawStatus(const char* message, uint16_t color) {
  tft.fillRect(0, 268, tft.width(), 9, TFT_BLACK);
  tft.setTextDatum(ML_DATUM);
  tft.setTextColor(wdAccent(), TFT_BLACK);
  tft.drawString(">", ART_X, 272, 1);
  tft.setTextColor(color, TFT_BLACK);
  tft.drawString(message, ART_X + 12, 272, 1);
  tft.setTextDatum(TL_DATUM);
}

// One bar cell per art column, so the readout lines up with the artwork.
void drawProgress(uint8_t complete) {
  for (uint8_t i = 0; i < ART_COLS; i++) {
    const bool on = i < complete;
    tft.drawChar(ART_X + i * CELL_W, 286, on ? 0xDB : 0xB0,
                 on ? wdAccent() : wdEdge(), TFT_BLACK, 1);
  }
}

void drawFooter(int16_t width) {
  for (int16_t i = 0; i < ART_COLS * CELL_W; i += 3)
    tft.drawPixel(ART_X + i, 300, wdEdge());
  tft.setTextDatum(MC_DATUM);
  tft.setTextColor(wdGrey(), TFT_BLACK);
  tft.drawString("ESP32-DIV V2  //  BASE: CIFERTECH", width / 2, 310, 1);
  tft.setTextDatum(TL_DATUM);
}

// The wordmark sits on its own plate under the art.
void drawWordMarkAt(int16_t y, bool framed) {
  const char* wordmark = "SHARKDIV";
  const int16_t mark_w = (int16_t)strlen(wordmark) * CELL_W * 2;
  const int16_t x = (tft.width() - mark_w) / 2;
  tft.fillRect(x - 8, y - 4, mark_w + 16, CELL_H + 9, TFT_BLACK);
  if (framed) {
    tft.drawRect(x - 8, y - 4, mark_w + 16, CELL_H + 9, wdEdge());
    wdCornerTicks(x - 8, y - 4, mark_w + 16, CELL_H + 9, 5, wdAccent());
  }
  tft.setTextDatum(TL_DATUM);
  tft.setTextColor(wdAccent(), TFT_BLACK);
  tft.drawString(wordmark, x, y, 2);
}

// Two sliced bands per frame: blanked, redrawn shifted, then restored.
const uint8_t GLITCH_BANDS = 2;
const int16_t GLITCH_HEIGHT = 2;

int16_t glitchRow(uint8_t band, uint16_t salt) {
  return (int16_t)(wdHash(band, salt, 0x3C3C) % (ART_ROWS - GLITCH_HEIGHT));
}

void drawGlitch(uint16_t salt) {
  for (uint8_t band = 0; band < GLITCH_BANDS; band++) {
    const uint16_t noise = wdHash(band, salt, 0x3C3C);
    const int16_t row = glitchRow(band, salt);
    const int16_t dx = ((noise >> 5) & 0x01) ? 4 : -4;
    clearRows(row, GLITCH_HEIGHT);
    drawArtRows(row, row + GLITCH_HEIGHT - 1, 0xFFFF, dx);
    churnNoise(row, row + GLITCH_HEIGHT - 1, salt);
  }
}

void restoreGlitch(uint16_t salt) {
  for (uint8_t band = 0; band < GLITCH_BANDS; band++) {
    const int16_t row = glitchRow(band, salt);
    clearRows(row, GLITCH_HEIGHT);
    drawArtRows(row, row + GLITCH_HEIGHT - 1, wdAccent());
  }
}

