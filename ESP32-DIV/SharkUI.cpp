// ── palette mapping: the boot follows whatever theme is active ──
// The whole boot sequence is phosphor green (user brand choice), regardless
// of the active menu theme.
static inline uint16_t wdAccent() { return 0x07E0; }     // bright green
static inline uint16_t wdAccentDim() { return 0x02E0; }
static inline uint16_t wdContent() { return 0x05E0; }
static inline uint16_t wdLabel() { return 0x05E0; }
static inline uint16_t wdGrey() { return 0x03E0; }
static inline uint16_t wdEdge() { return 0x02E0; }
static inline uint16_t wdWarn() { return 0x07E0; }
static inline uint16_t wdMarkA() { return 0x07E0; }
static inline uint16_t wdMarkB() { return 0x05E0; }
static inline uint16_t wdMarkC() { return 0x03E0; }

// Deterministic 16 bit hash. The splash uses it instead of a frame buffer so
// every character cell can be recomputed identically on demand.
static inline uint16_t wdHash(uint16_t x, uint16_t y, uint16_t salt) {
  uint32_t h = (uint32_t)x * 73856093UL ^ (uint32_t)y * 19349663UL ^
               (uint32_t)salt * 83492791UL;
  h ^= h >> 13;
  h *= 2654435761UL;
  h ^= h >> 16;
  return (uint16_t)h;
}

// Two opposite L-shaped ticks. Cheaper than a full frame and survives the
// panel's viewing angle better than a 1 px outline alone.
static void wdCornerTicks(int16_t x, int16_t y, int16_t w, int16_t h,
                          int16_t arm, uint16_t color) {
  if (w < arm * 2 || h < arm * 2)
    return;
  tft.drawFastHLine(x, y, arm, color);
  tft.drawFastVLine(x, y, arm, color);
  tft.drawFastHLine(x + w - arm, y, arm, color);
  tft.drawFastVLine(x + w - 1, y, arm, color);
  tft.drawFastHLine(x, y + h - 1, arm, color);
  tft.drawFastVLine(x, y + h - arm, arm, color);
  tft.drawFastHLine(x + w - arm, y + h - 1, arm, color);
  tft.drawFastVLine(x + w - 1, y + h - arm, arm, color);
}

// ── ctOS menu tile ─────────────────────────────────────────────────────
void drawSharkTile(int16_t x, int16_t y, int16_t w, int16_t h, bool selected) {
  tft.startWrite();
  tft.fillRect(x, y, w, h, UI.fg);
  if (selected) {
    tft.drawRect(x, y, w, h, UI.icon);
    // Accent rail on the leading edge + corner ticks: the ctOS focus mark.
    tft.fillRect(x, y, 3, h, UI.icon);
    wdCornerTicks(x + 3, y, w - 3, h, 5, UI.accent);
  } else {
    tft.drawRect(x, y, w, h, UI.line);
  }
  tft.endWrite();
}

// List rows (submenus): selected row gets a leading accent rail.
void drawSharkRowRail(int16_t y, int16_t h, bool selected) {
  tft.startWrite();
  tft.fillRect(0, y, 4, h, selected ? UI.accent : UI_BG);
  tft.endWrite();
}

