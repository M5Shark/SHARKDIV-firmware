static int CW, CH, BAR_H, COLS, ROWS, OX, OY, SW, SH;
static const uint8_t* FONT;

enum { A_GLYPH = 0, A_CURSOR, A_HEAD, A_FLASH, A_T1, A_T2, A_T3 };
static uint16_t PAL[7];
static uint16_t C_BAR, C_BLACK;

static uint8_t* skullGrid[2];
static uint8_t* gch;
static uint8_t* gattr;

struct Drop { float t0, speed; uint8_t len; bool on; };
struct Column { float melt0; Drop main, extra; };
static Column* colv;

static const char RAIN[] = "$S7?Ii!;:,.`'jdLk%\177\201";
static const int NRAIN = sizeof(RAIN) - 1;
static const float GRAVITY = 70.0f;

static TFT_eSprite* s_spr = nullptr;
static bool s_sprOk = false;

static inline float frand() { return (float)(esp_random() & 0xFFFFFF) / 16777216.0f; }
static inline uint8_t rainGlyph(int c, int r, int slot) {
  uint32_t h = (uint32_t)c * 73856093u ^ (uint32_t)r * 19349663u ^ (uint32_t)slot * 83492791u;
  h ^= h >> 13; h *= 0x5bd1e995u; h ^= h >> 15;
  return (uint8_t)RAIN[h % NRAIN];
}

static void drawGlyphPx(int x0, int y0, uint8_t ch, uint16_t fg) {
  if (ch < 33 || ch > 132) return;
  const uint8_t* g = FONT + (ch - 32) * CH;
  for (int y = 0; y < CH; y++) {
    uint8_t b = pgm_read_byte(g + y);
    if (!b) continue;
    for (int x = 0; x < CW; x++)
      if (b & (0x80 >> x)) s_spr->drawPixel(x0 + x, y0 + y, fg);
  }
}

static void drawModeline(const char* name, bool arrow) {
  s_spr->fillRect(0, SH - BAR_H, SW, BAR_H, C_BAR);
  char buf[48];
  snprintf(buf, sizeof(buf), arrow ? "-UUU:**--F1  >> %s" : "-UUU:**--F1  %s", name);
  int x = CW / 2;
  for (const char* s2 = buf; *s2; s2++, x += CW) drawGlyphPx(x, SH - BAR_H, (uint8_t)*s2, C_BLACK);
}

static void flushGrid() {
  for (int r = 0; r < ROWS; r++)
    for (int c = 0; c < COLS; c++) {
      int k = r * COLS + c;
      int x = OX + c * CW, y = OY + r * CH;
      if (gattr[k] == A_CURSOR) {
        s_spr->fillRect(x, y, CW, CH, PAL[A_GLYPH]);
        drawGlyphPx(x, y, gch[k], C_BLACK);
      } else if (gch[k] != ' ') {
        drawGlyphPx(x, y, gch[k], PAL[gattr[k]]);
      }
    }
}

static void clearGrid() {
  memset(gch, ' ', COLS * ROWS);
  memset(gattr, A_GLYPH, COLS * ROWS);
}

static void layoutSkull(int k) {
  const Skull& s = SKULLS[k];
  int w = 0;
  for (int r = 0; r < s.n; r++) w = max(w, (int)strlen(s.lines[r]));
  int ox = (COLS - w) / 2, oy = (ROWS - s.n) / 2;
  skullGrid[k] = (uint8_t*)malloc(COLS * ROWS);
  memset(skullGrid[k], ' ', COLS * ROWS);
  for (int r = 0; r < s.n; r++)
    for (int c = 0; s.lines[r][c]; c++)
      skullGrid[k][(r + oy) * COLS + (c + ox)] = (uint8_t)s.lines[r][c];
}

static float morphEnd = 0;
static uint32_t morphStart = 0;

static void startMorph() {
  morphEnd = 0;
  for (int c = 0; c < COLS; c++) {
    Column& col = colv[c];
    bool hasNew = false;
    for (int r = 0; r < ROWS; r++) if (skullGrid[1][r * COLS + c] != ' ') { hasNew = true; break; }
    col.melt0 = (float)c / COLS * 0.45f + frand() * 0.3f;
    col.main.t0 = col.melt0 + 0.35f + frand() * 0.35f;
    col.main.speed = 16 + frand() * 10;
    col.main.len = 6 + (esp_random() % 8);
    col.main.on = hasNew || frand() < 0.6f;
    col.extra.t0 = col.main.t0 + 0.3f + frand() * 0.7f;
    col.extra.speed = 20 + frand() * 12;
    col.extra.len = 3 + (esp_random() % 5);
    col.extra.on = frand() < 0.55f;
    float mainEnd = col.main.t0 + (ROWS + col.main.len + 2) / col.main.speed;
    float extraEnd = col.extra.on ? col.extra.t0 + (ROWS + col.extra.len + 2) / col.extra.speed : 0;
    float meltEnd = col.melt0 + ROWS * 0.025f + sqrtf(2.0f * ROWS / GRAVITY) + 0.1f;
    morphEnd = fmaxf(morphEnd, fmaxf(mainEnd, fmaxf(extraEnd, meltEnd)));
  }
  morphStart = millis();
}

static inline float headRow(const Drop& d, float tau) { return (tau - d.t0) * d.speed - 1; }

static void drawDrop(int c, const Drop& d, float tau, int slot, bool bright) {
  if (!d.on || tau < d.t0) return;
  int h = (int)floorf(headRow(d, tau));
  const uint8_t* nw = skullGrid[1];
  for (int k = 0; k <= d.len; k++) {
    int r = h - k;
    if (r < 0 || r >= ROWS) continue;
    int i = r * COLS + c;
    bool locked = nw[i] != ' ' && r < headRow(colv[c].main, tau);
    if (k == 0) {
      gch[i] = rainGlyph(c, r, slot);
      gattr[i] = A_HEAD;
    } else if (locked) {
      gch[i] = nw[i];
      gattr[i] = k <= 2 ? A_FLASH : A_GLYPH;
    } else {
      gch[i] = rainGlyph(c, r, slot + k);
      float f = (float)k / d.len;
      gattr[i] = f < 0.34f ? A_T1 : (f < 0.67f ? A_T2 : A_T3);
      if (!bright && gattr[i] == A_T1) gattr[i] = A_T2;
    }
  }
}

static void drawStatic(int which) {
  clearGrid();
  memcpy(gch, skullGrid[which], COLS * ROWS);
  s_spr->fillSprite(C_BLACK);
  flushGrid();
  drawModeline(SKULLS[which].name, false);
  s_spr->pushSprite(0, 0);
}

static void drawMorph() {
  float tau = (millis() - morphStart) / 1000.0f;
  int slot = (int)(tau * 12);
  const uint8_t* old = skullGrid[0];
  const uint8_t* nw = skullGrid[1];
  clearGrid();

  for (int c = 0; c < COLS; c++) {
    float h = headRow(colv[c].main, tau);
    for (int r = 0; r < ROWS && r < h; r++) {
      int i = r * COLS + c;
      if (nw[i] != ' ') { gch[i] = nw[i]; gattr[i] = A_GLYPH; }
    }
  }
  for (int c = 0; c < COLS; c++) {
    drawDrop(c, colv[c].main, tau, slot, true);
    drawDrop(c, colv[c].extra, tau, slot + 101, false);
  }
  for (int c = 0; c < COLS; c++) {
    for (int r = ROWS - 1; r >= 0; r--) {
      uint8_t ch = old[r * COLS + c];
      if (ch == ' ') continue;
      float start = colv[c].melt0 + (ROWS - 1 - r) * 0.025f;
      int y = r;
      if (tau > start) {
        float dt = tau - start;
        y = (int)lroundf(r + 0.5f * GRAVITY * dt * dt);
        if (((esp_random() & 0xFF) < 90)) ch = rainGlyph(c, r, slot + 7);
      }
      if (y >= ROWS) continue;
      int i = y * COLS + c;
      if (gattr[i] == A_HEAD) continue;
      gch[i] = ch;
      gattr[i] = A_GLYPH;
      if (tau > start + 0.05f && y - 1 >= 0) {
        int j = (y - 1) * COLS + c;
        if (gch[j] == ' ') { gch[j] = rainGlyph(c, y, slot); gattr[j] = A_T3; }
      }
    }
  }

  s_spr->fillSprite(C_BLACK);
  flushGrid();
  drawModeline(SKULLS[1].name, true);
  s_spr->pushSprite(0, 0);
}

// One full boot pass: rest on skull A, melt into skull B under green rain,
// brief hold. ~4 s total.
void run() {
  tft.fillScreen(TFT_BLACK);
  SW = tft.width(); SH = tft.height();
  if (SW >= 25 * 8 && SH >= 18 * 16 + 16) { CW = 8; CH = 16; FONT = &FONT8x16[0][0]; }
  else { CW = 6; CH = 12; FONT = &FONT6x12[0][0]; }
  BAR_H = CH;
  COLS = SW / CW;
  ROWS = (SH - BAR_H) / CH;
  OX = (SW - COLS * CW) / 2;
  OY = (SH - BAR_H - ROWS * CH) / 2;
  if (COLS < 25 || ROWS < 16) return;  // screen too small, skip gracefully

  TFT_eSprite spr(&tft);
  spr.setColorDepth(16);
  s_sprOk = (spr.createSprite(SW, SH) != nullptr);
  s_spr = s_sprOk ? &spr : nullptr;
  if (!s_sprOk) return;  // no memory for the frame buffer: skip the show

  // Phosphor green everything, per the boot palette.
  PAL[A_GLYPH]  = tft.color565(120, 255, 150);
  PAL[A_CURSOR] = PAL[A_GLYPH];
  PAL[A_HEAD]   = tft.color565(220, 255, 220);
  PAL[A_FLASH]  = tft.color565(170, 255, 170);
  PAL[A_T1]     = tft.color565(40, 220, 70);
  PAL[A_T2]     = tft.color565(20, 150, 45);
  PAL[A_T3]     = tft.color565(10, 80, 25);
  C_BAR   = tft.color565(40, 200, 80);
  C_BLACK = TFT_BLACK;

  gch = (uint8_t*)malloc(COLS * ROWS);
  gattr = (uint8_t*)malloc(COLS * ROWS);
  colv = (Column*)calloc(COLS, sizeof(Column));
  layoutSkull(0);
  layoutSkull(1);

  drawStatic(0);
  delay(600);
  startMorph();
  while ((millis() - morphStart) / 1000.0f < morphEnd) {
    drawMorph();
    delay(40);
  }
  drawStatic(1);
  delay(700);

  free(gch); free(gattr); free(colv);
  free(skullGrid[0]); free(skullGrid[1]);
  spr.deleteSprite();
  s_spr = nullptr;
  tft.fillScreen(TFT_BLACK);
}

