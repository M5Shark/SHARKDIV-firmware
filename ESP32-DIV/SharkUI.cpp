void playSharkBoot() {
  applyThemeToPalette(settings().theme);

  const int16_t width = tft.width();
  tft.fillScreen(TFT_BLACK);
  drawHeader(width);
  drawFooter(width);
  drawStatus("BOOTING", wdGrey());
  drawProgress(0);

  // The user's Skull Rain screen: melt + green rain, then the logo reveal.
  SkullRain::run();

  // 5. The M5SHARK mark: the shark-head logo wipes in behind a bright scan
  // bar, pulses, and the brand + version settle under it.
  const int16_t LOGO_X = (width - SHARK_LOGO_W) / 2;
  const int16_t LOGO_Y = 58;
  const int16_t logoBytes = (SHARK_LOGO_W + 7) / 8;
  auto logoColumns = [&](int16_t fromX, int16_t toX, uint16_t color) {
    for (int16_t x = fromX; x < toX && x < SHARK_LOGO_W; x++) {
      for (int16_t y = 0; y < SHARK_LOGO_H; y++) {
        const uint8_t bits = pgm_read_byte(&shark_logo_bitmap[y * logoBytes + (x >> 3)]);
        if (bits & (128 >> (x & 7))) {
          tft.drawPixel(LOGO_X + x, LOGO_Y + y, color);
        }
      }
    }
  };

  clearRows(0, ART_ROWS);
  drawStatus("IDENTITY VERIFIED", wdLabel());

  // Wipe the mark in ten bands, bright leading edge, dark fill behind.
  constexpr int16_t kLogoBands = 10;
  const int16_t bandW = SHARK_LOGO_W / kLogoBands;
  for (int16_t band = 0; band < kLogoBands; band++) {
    const int16_t x1 = (band + 1) * bandW;
    logoColumns(band * bandW, x1, wdAccent());
    tft.drawFastVLine(LOGO_X + x1 - 1, LOGO_Y, SHARK_LOGO_H, 0xFFFF);
    delay(24);
    tft.drawFastVLine(LOGO_X + x1 - 1, LOGO_Y, SHARK_LOGO_H, TFT_BLACK);
  }

  // Bright pulse, then settle.
  logoColumns(0, SHARK_LOGO_W, 0xFFFF);
  delay(90);
  logoColumns(0, SHARK_LOGO_W, wdAccent());

  // Brand block under the mark.
  tft.setTextDatum(MC_DATUM);
  tft.setTextColor(wdAccent(), TFT_BLACK);
  tft.drawString("SHARKDIV", width / 2, 218, 3);
  tft.setTextColor(wdContent(), TFT_BLACK);
  tft.drawString(String("ESP32-S3 MULTITOOL  ") + ESP32DIV_VERSION, width / 2, 246, 1);
  tft.setTextDatum(TL_DATUM);
  wdCornerTicks(LOGO_X - 8, LOGO_Y - 8, SHARK_LOGO_W + 16, 140 + 16, 5, wdAccent());
  drawStatus("M5SHARK", wdAccent());
  drawProgress(ART_COLS);
  delay(950);
}
