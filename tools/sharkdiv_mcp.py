def app_create(name, desc):
    fname = _re.sub(r"[^a-z0-9_]", "", name.lower().replace(" ", "_"))
    ns = fname.title().replace("_", "") + "App"
    title = name.strip()
    if not fname:
        return "invalid app name"
    app_file = SKETCH + f"/UserApp_{fname}.cpp"
    open(app_file, "w").write(APP_TEMPLATE.format(
        fname=fname, ns=ns, title=title, TITLE=title.upper(),
        desc=desc or "generated app"))
    h = open(SKETCH + "/UserApps.h").read()
    if f"namespace {ns} " not in h:
        h = h.replace("// === generated app declarations (app builder writes below this line) ===",
                      f"// === generated app declarations (app builder writes below this line) ===\n"
                      f"namespace {ns} {{\n  void appSetup();\n  void appLoop();\n  void exit();\n}}")
        open(SKETCH + "/UserApps.h", "w").write(h)
    c = open(SKETCH + "/UserApps.cpp").read()
    if f'"{title}"' not in c:
        c = c.replace('// === generated includes (app builder writes below this line) ===',
                      f'// === generated includes (app builder writes below this line) ===\n#include "UserApp_{fname}.h"')
        # include the .cpp directly from UserApps.cpp (simplest linkage)
        c = c.replace('#include "UserApps.cpp_generated"', '')
        c = c.replace('// === generated includes (app builder writes below this line) ===\n#include "UserApp_' + fname + '.h"',
                      f'// === generated includes (app builder writes below this line) ===\n#include "UserApp_{fname}.cpp"')
        c = c.replace('SHARKDIV_APP("Demo App", DemoApp::appSetup, DemoApp::appLoop, DemoApp::exit) \\',
                      f'SHARKDIV_APP("Demo App", DemoApp::appSetup, DemoApp::appLoop, DemoApp::exit) \\\n'
                      f'  SHARKDIV_APP("{title}", {ns}::appSetup, {ns}::appLoop, {ns}::exit) \\')
        open(SKETCH + "/UserApps.cpp", "w").write(c)
    return f"app '{title}' written ({app_file}) — call sharkdiv_app_build"

def app_build():
    r = _sp.run(BUILD, capture_output=True, text=True, timeout=600)
    tail = (r.stdout + r.stderr).strip().split("\n")
    ok = "Sketch uses" in (r.stdout + r.stderr)
    key = [l for l in tail if "error" in l.lower() or "Sketch uses" in l or "Done:" in l]
    return ("BUILD OK\n" if ok else "BUILD FAILED\n") + "\n".join(key[-8:])

def app_flash():
    b = app_build()
    if not b.startswith("BUILD OK"):
        return b + "\n(not flashing)"
    global _ser
    if _ser:
        _ser.close()
        _ser = None
    r = _sp.run(UPLOAD, capture_output=True, text=True, timeout=600)
    tail = (r.stdout + r.stderr).strip().split("\n")[-3:]
    return b + "\nFLASH: " + "\n".join(tail)

