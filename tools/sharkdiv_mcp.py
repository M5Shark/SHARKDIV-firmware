def handle(name, args):
    if name == "sharkdiv_press":
        key = args["key"][0].lower()
        det = args.get("deterministic", True)
        out = cmd(key.upper() if det else key, 0.6)
        return state()
    if name == "sharkdiv_state":
        return state()
    if name == "sharkdiv_battery":
        return "\n".join(l for l in cmd("b", 0.6).split("\n") if "[mcp]" in l) or "(no reply)"
    if name == "sharkdiv_reset":
        return reset()
    if name == "sharkdiv_log":
        secs = float(args.get("seconds", 3))
        s = ser()
        out = ""
        t0 = time.time()
        while time.time() - t0 < secs:
            out += s.read(4096).decode("utf-8", "replace")
        return out[-2000:] or "(silence)"
    if name == "sharkdiv_app_list":
        c = open(SKETCH + "/UserApps.cpp").read()
        apps = _re.findall(r'SHARKDIV_APP\("([^"]+)"', c)
        return f"{len(apps)} apps: " + ", ".join(apps) + f" (slots: 4 max)"
    if name == "sharkdiv_app_create":
        return app_create(args["name"], args.get("description", ""))
    if name == "sharkdiv_app_build":
        return app_build()
    if name == "sharkdiv_app_flash":
        out = app_flash()
        return out + "\nboot: " + reset()[-300:]
    if name == "sharkdiv_run":
        return run_tool(args["menu"], args["item"], float(args.get("watch", 6)))
    return f"unknown tool {name}"

def main():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            req = json.loads(line)
        except Exception:
            continue
        method = req.get("method", "")
        rid = req.get("id")
        if method == "initialize":
            resp = {"jsonrpc": "2.0", "id": rid, "result": {
                "protocolVersion": req.get("params", {}).get("protocolVersion", "2024-11-05"),
                "capabilities": {"tools": {}},
                "serverInfo": {"name": "sharkdiv", "version": "1.0.0"}}}
        elif method == "notifications/initialized":
            continue
        elif method == "tools/list":
            resp = {"jsonrpc": "2.0", "id": rid, "result": {"tools": TOOLS}}
        elif method == "tools/call":
            try:
                text = handle(req["params"]["name"], req["params"].get("arguments", {}))
                result = {"content": [{"type": "text", "text": text}]}
            except Exception as e:
                result = {"content": [{"type": "text", "text": f"error: {e}"}], "isError": True}
            resp = {"jsonrpc": "2.0", "id": rid, "result": result}
        elif rid is not None:
            resp = {"jsonrpc": "2.0", "id": rid,
                    "error": {"code": -32601, "message": f"unknown method {method}"}}
        else:
            continue
        sys.stdout.write(json.dumps(resp) + "\n")
        sys.stdout.flush()

if __name__ == "__main__":
    main()
