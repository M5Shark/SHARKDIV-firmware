#!/usr/bin/env python3
"""SHARKDIV MCP server — remote test bridge for the SHARKDIV device.

Firmware side (v1.7.22+): a serial console task on the device accepts
single-letter commands and reports state. This server exposes them as MCP
tools so an agent can drive and verify the real hardware:

  u/d/l/r/k  tap nav bar (touch-emulating)     U/D/L/R/K  single-step (deterministic)
  s          state report                      b          battery gauge
"""
import json, os, sys, time
import serial

PORT = os.environ.get("SHARKDIV_PORT", "/dev/cu.usbserial-210")
BAUD = 115200

_ser = None

def ser():
    global _ser
    if _ser is None or not _ser.is_open:
        _ser = serial.Serial(PORT, BAUD, timeout=1)
    return _ser

def cmd(c, wait=0.55):
    s = ser()
    s.write(c.encode())
    time.sleep(wait)
    return s.read(8192).decode("utf-8", "replace")

def state():
    for line in cmd("s", 0.4).split("\n"):
        if line.startswith("[mcp] v="):
            return line.strip()
    return "(no state — is the device on?)"

def reset():
    s = ser()
    s.reset_input_buffer()
    s.setDTR(False)
    s.setRTS(True)
    time.sleep(0.15)
    s.setRTS(False)
    out = ""
    t0 = time.time()
    while time.time() - t0 < 30:
        out += s.read(4096).decode("utf-8", "replace")
        if "[boot] ready" in out:
            break
    return out[-1500:]

def parse(st):
    try:
        menu = int(st.split("menu=")[1].split("(")[0])
        sub = int(st.split("sub=")[1].split("(")[0])
        feat = int(st.split("feature=")[1].split()[0])
        name = st.split("sub=")[1].split("(")[1].split(")")[0]
        return menu, sub, feat, name
    except Exception:
        return None

# menu tile -> index (main menu grid: col1 rows 0-3, col2 rows 4-7)
MENUS = {"wifi": 0, "2.4ghz": 1, "nrf": 1, "more": 2, "settings": 3,
         "bluetooth": 4, "subghz": 5, "tools": 6, "about": 7}

def goto_menu(target):
    for _ in range(14):
        p = parse(state())
        if p is None:
            return False
        menu, sub, feat, name = p
        if feat:
            cmd("K", 1.0)          # escape any running feature
            continue
        if menu == target:
            return True
        if (menu < 4) != (target < 4):
            cmd("R" if target >= 4 else "L", 0.6)
        else:
            cmd("D" if target > menu else "U", 0.6)
    return False

def run_tool(menu, item, watch=6.0):
    """Navigate to a menu, select item by NAME substring, launch it.
    Verifies the submenu actually opened; retries the whole sequence if a
    tap raced the UI redraw."""
    target = MENUS.get(menu.lower().strip())
    if target is None:
        return f"unknown menu '{menu}' (try: {', '.join(MENUS)})"
    want = item.lower().strip()
    launched = False
    for attempt in range(3):
        if not goto_menu(target):
            continue
        cmd("K", 1.2)              # open the submenu
        ok_sub = False
        for _ in range(12):
            p = parse(state())
            if p is None:
                continue
            m, sub, feat, name = p
            if feat:
                launched = True
                break
            if m != target or name == "-":
                break              # tap raced the redraw; retry
            ok_sub = True
            if want in name.lower():
                break
            cmd("D", 0.5)
        if launched or ok_sub:
            break
    if not launched:
        cmd("K", 1.5)              # launch the selected item
    cmd("K", max(watch, 2.0))      # launch + let it run
    s = ser()
    out = ""
    t0 = time.time()
    while time.time() - t0 < 3:
        out += s.read(4096).decode("utf-8", "replace")
        time.sleep(0.2)
    return "state: " + state() + "\nlog:\n" + "\n".join(
        l for l in out.split("\n") if l.strip())[-1500:]


